package maxigregrze.cobblesafari.block.base;

import com.mojang.serialization.MapCodec;
import net.minecraft.core.BlockPos;
import net.minecraft.core.Direction;
import net.minecraft.world.level.BlockGetter;
import net.minecraft.world.level.block.StairBlock;
import net.minecraft.world.level.block.state.BlockState;
import net.minecraft.world.level.block.state.properties.Half;
import net.minecraft.world.level.block.state.properties.StairsShape;
import net.minecraft.world.phys.shapes.CollisionContext;
import net.minecraft.world.phys.shapes.VoxelShape;

import java.util.EnumMap;
import java.util.Map;

/**
 * A ridge: the high step of a stair without its slab - half a block on one side of the cell, 8px
 * tall, at the bottom or (upside down) the top of the cell (plan 194 - 9).
 *
 * <p>Everything but the shape is a vanilla stair: placement, corners, waterlogging, structure
 * rotation, and so a ridge also bends against real stairs, which is what a roof wants. The
 * blockstates are generated by {@code .private/generate_ridge_assets.py} from the same quarters.</p>
 */
public class RidgeBlock extends StairBlock {

    private static final Map<Half, Map<StairsShape, Map<Direction, VoxelShape>>> SHAPES = buildShapes();

    private final BlockState ridgeBaseState;

    public RidgeBlock(BlockState baseState, Properties properties) {
        super(baseState, properties);
        this.ridgeBaseState = baseState;
    }

    private static Map<Half, Map<StairsShape, Map<Direction, VoxelShape>>> buildShapes() {
        Map<Half, Map<StairsShape, Map<Direction, VoxelShape>>> out = new EnumMap<>(Half.class);
        for (Half half : Half.values()) {
            double minY = half == Half.TOP ? 8 : 0;
            Map<StairsShape, Map<Direction, VoxelShape>> byShape = new EnumMap<>(StairsShape.class);
            for (StairsShape shape : StairsShape.values()) {
                Map<Direction, VoxelShape> byFacing = new EnumMap<>(Direction.class);
                for (Direction facing : Direction.Plane.HORIZONTAL) {
                    byFacing.put(facing, StairShapeLogic.stepQuarters(facing, shape, minY, minY + 8).optimize());
                }
                byShape.put(shape, byFacing);
            }
            out.put(half, byShape);
        }
        return out;
    }

    @Override
    public MapCodec<? extends StairBlock> codec() {
        return simpleCodec(props -> new RidgeBlock(this.ridgeBaseState, props));
    }

    @Override
    protected VoxelShape getShape(BlockState state, BlockGetter level, BlockPos pos, CollisionContext context) {
        return SHAPES.get(state.getValue(HALF)).get(state.getValue(SHAPE)).get(state.getValue(FACING));
    }
}
